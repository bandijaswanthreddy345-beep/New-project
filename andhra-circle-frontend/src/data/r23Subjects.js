/**
 * Intelligent credit detector:
 * Given a subject title typed by the user, returns its official R23 credits.
 * If not an exact match, looks for partial match or infers based on course nature.
 */
export function detectSubjectCredits(subjectName) {
  if (!subjectName || typeof subjectName !== "string") return 3.0;

  const normalized = subjectName.trim().toLowerCase();

  // 1. Direct match in official dictionary
  if (GLOBAL_SUBJECT_CREDIT_MAP[normalized] !== undefined) {
    return GLOBAL_SUBJECT_CREDIT_MAP[normalized];
  }

  // 2. Substring matching against official subjects
  for (const [key, creds] of Object.entries(GLOBAL_SUBJECT_CREDIT_MAP)) {
    if (normalized.length >= 4 && (key.includes(normalized) || normalized.includes(key))) {
      return creds;
    }
  }

  // 3. Intelligent rule-based heuristic inference
  if (
    normalized.includes("lab") ||
    normalized.includes("laboratory") ||
    normalized.includes("practical") ||
    normalized.includes("workshop")
  ) {
    return 1.5;
  }

  if (
    normalized.includes("project") ||
    normalized.includes("seminar") ||
    normalized.includes("internship") ||
    normalized.includes("skill")
  ) {
    return 2.0;
  }

  if (
    normalized.includes("yoga") ||
    normalized.includes("wellness") ||
    normalized.includes("nss") ||
    normalized.includes("ncc") ||
    normalized.includes("environmental") ||
    normalized.includes("audit")
  ) {
    return 0.5;
  }

  if (normalized.includes("internship / major project") || normalized.includes("capstone project")) {
    return 12.0;
  }

  // Default theory standard course
  return 3.0;
}

